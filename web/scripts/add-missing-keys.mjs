async function main() {
  for (const lang of LOCALES) {
    const filePath = path.join(LOCALES_DIR, `${lang}.json`)
    try {
      const content = await fs.readFile(filePath, 'utf-8')
      const json = JSON.parse(content)

      for (const [key, translations] of Object.entries(newKeys)) {
        json[key] = translations[lang] || translations.en || key
      }

      await fs.writeFile(filePath, `${JSON.stringify(json, null, 2)  }\n`, 'utf-8')
      console.log(`Updated ${lang}.json`)
    } catch (err) {
      console.error(`Failed to update ${lang}.json:`, err)
    }
  }
  console.log('Finished updating all locale files.')
}

main()
